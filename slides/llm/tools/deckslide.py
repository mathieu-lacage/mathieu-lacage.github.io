"""Shared by the slide generators: print a generated slide, or put it in the
deck; write a figure as a standalone SVG in themes/; group the logit-lens
layers by top-1 token (the stack drawn by lens_slide.py and attn_slide.py).

A generated slide is found again by the marker comment it carries in its
style ("generated by tools/<script>"), so moving or retitling it is fine.
"""
import hashlib
import html
import os
import re
import sys


def emit(slide, marker, deck=None, after=None):
    """deck None: print the slide. Otherwise replace the slide carrying marker;
    if there is none yet, insert it right after the slide carrying after."""
    if deck is None:
        print(slide)
        return
    slides = open(deck).read().split('\n---\n')
    mine = [k for k, t in enumerate(slides) if marker in t]
    if len(mine) > 1:
        sys.exit(f'{deck}: {len(mine)} slides carry {marker!r}')
    if mine:
        k = mine[0]
        slides[k] = slide + '\n\n'
    else:
        prev = [k for k, t in enumerate(slides) if after and after in t]
        if len(prev) != 1:
            sys.exit(f'{deck}: no slide carries {marker!r} and no single slide carries {after!r} to insert after')
        k = prev[0] + 1
        slides.insert(k, slide + '\n\n')
    open(deck, 'w').write('\n---\n'.join(slides))
    print(f'{deck}: {"updated" if mine else "inserted"} slide {k}')


THEMES = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'themes')


def palette():
    """the --cutebugs-* colours of the deck theme, so a standalone SVG matches it"""
    css = open(os.path.join(THEMES, 'cutebugs.css')).read()
    return dict(re.findall(r'(--cutebugs-[a-z-]+):\s*(#[0-9a-fA-F]{3,8})', css))


def write_svg(name, width, height, css, body):
    """write themes/<name> as a standalone SVG document (theme colours and font
    included, since the deck's CSS does not reach into an <object>) and return
    the markdown that includes it"""
    root = ' '.join(f'{k}: {v};' for k, v in palette().items())
    doc = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" '
           f'width="{width:.0f}" height="{height:.0f}">\n<style><![CDATA[\n'
           "@import url('https://fonts.googleapis.com/css2?family=IBM+Plex+Sans:wght@400;600&family=IBM+Plex+Mono:wght@500&display=swap');\n"
           f"svg {{ {root} font-family: 'IBM Plex Sans', 'Helvetica Neue', Arial, sans-serif; }}\n"
           f'{css}\n]]></style>\n{body}\n</svg>\n')
    with open(os.path.join(THEMES, name), 'w') as f:
        f.write(doc)
    # the content hash in the URL makes browsers reload the figure when it changes
    v = hashlib.sha1(doc.encode()).hexdigest()[:8]
    return (f'<object class="figure" type="image/svg+xml" data="themes/{name}?v={v}" '
            f'width="{width:.0f}" height="{height:.0f}"></object>')


def word(t):
    """a token as the slides show it: leading space as ␣, escaped for SVG"""
    return html.escape(t.replace(' ', '␣'))


NOISE_UNTIL = 9   # layers 1..9 predict junk tokens (ertas, _rgba, _dyn…): one group


def lens_groups(d):
    """the layers of lens2d.py's data d (one row per layer, bottom-up) and their
    groups: consecutive layers with the same top-1 token, the junk tokens of the
    first NOISE_UNTIL layers making one group. Each group is a dict: a, b (first
    and last row index), name (its label) and cls ('fr' for the target, 'noise'
    or '')."""
    rows = [r for r in d['steps'] if r['kind'] == 'ffn']
    target = word(d['target'])

    def top1(r):
        return target if r['target_rank'] == 1 else word(r['competitor'])

    spans = []
    for k, r in enumerate(rows):
        if spans and (top1(r) == top1(rows[spans[-1][1]]) or r['layer'] <= NOISE_UNTIL):
            spans[-1][1] = k
        else:
            spans.append([k, k])
    groups = []
    for a, b in spans:
        if rows[b]['layer'] <= NOISE_UNTIL and b > a:
            seen = list(dict.fromkeys(top1(r) for r in rows[a:b + 1]))
            name, cls = 'noise: ' + ', '.join(seen[:3]) + '…', 'noise'
        else:
            name = top1(rows[a])
            cls = 'fr' if name == target else ''
        groups.append({'a': a, 'b': b, 'name': name, 'cls': cls})
    return rows, groups
